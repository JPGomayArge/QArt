#!/usr/bin/env node
// Merge scripts/overrides.mjs into src/data/images.ts — fully offline, no network.
// The Commons Special:FilePath URL is deterministic, so no lookups are needed.
//
//   node scripts/apply-overrides.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { IMAGE_OVERRIDES } from './overrides.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const IMAGES_TS = path.resolve(__dirname, '../src/data/images.ts');
const ARTWORKS_TS = path.resolve(__dirname, '../src/data/artworks.ts');

// Current catalog ids, so we can drop orphan image entries (works that were
// renamed or replaced no longer have a matching artwork).
const catalogIds = new Set(
  [...fs.readFileSync(ARTWORKS_TS, 'utf8').matchAll(/\{ id: "((?:[^"\\]|\\.)*)"/g)].map((m) =>
    JSON.parse(`"${m[1]}"`)
  )
);

const commonsUrl = (f) =>
  'https://commons.wikimedia.org/wiki/Special:FilePath/' +
  encodeURIComponent(f.replace(/ /g, '_')) +
  '?width=1400';

function loadKV(file) {
  const map = {};
  if (!fs.existsSync(file)) return map;
  const re = /"([^"]+)":\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(fs.readFileSync(file, 'utf8')))) map[m[1]] = m[2];
  return map;
}

function writeImages(map) {
  const entries = Object.keys(map)
    .sort()
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(map[id])},`)
    .join('\n');
  fs.writeFileSync(
    IMAGES_TS,
    `// Baked, verified public-domain image URLs (Wikimedia Commons), keyed by
// artwork id. Generated by scripts/fetch-images.mjs — do not edit by hand.
// Matched via Wikipedia + Wikidata creator verification; only free Commons images.
// Copyrighted works have no entry and fall back to the in-app placeholder.

export const ARTWORK_IMAGES: Record<string, string> = {\n${entries}\n};\n`,
    'utf8'
  );
}

const images = loadKV(IMAGES_TS);
let added = 0;
for (const [id, file] of Object.entries(IMAGE_OVERRIDES)) {
  images[id] = commonsUrl(file);
  added++;
}
// Prune orphans (ids no longer in the catalog).
let pruned = 0;
for (const id of Object.keys(images)) {
  if (!catalogIds.has(id)) {
    delete images[id];
    pruned++;
  }
}
writeImages(images);
console.log(
  `Applied ${added} overrides · pruned ${pruned} orphans · images.ts now has ${Object.keys(images).length} entries`
);
