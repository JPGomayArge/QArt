/**
 * Format a work's dimensions in the requested unit, or undefined if unknown.
 * Stored values are height × width in cm.
 */
export function formatDimensions(id: string, unit: 'cm' | 'in'): string | undefined {
  const d = DIMENSIONS[id];
  if (!d) return undefined;
  const [h, w] = d;
  if (unit === 'in') {
    const toIn = (n: number) => Math.round((n / 2.54) * 10) / 10;
    return `${toIn(h)} × ${toIn(w)} in`;
  }
  return `${h} × ${w} cm`;
}
